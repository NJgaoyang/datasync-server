CREATE DATABASE IF NOT EXISTS datasync DEFAULT CHARACTER SET utf8mb4;
USE datasync;

CREATE TABLE IF NOT EXISTS datasource (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(20) NOT NULL COMMENT 'mysql/starrocks',
    host VARCHAR(100) NOT NULL,
    port INT NOT NULL,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(200) NOT NULL,
    database_name VARCHAR(100) DEFAULT NULL,
    description VARCHAR(500) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sync_task (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    task_name VARCHAR(200) NOT NULL,
    sync_type VARCHAR(20) NOT NULL COMMENT 'batch/realtime',
    engine VARCHAR(20) NOT NULL DEFAULT 'ZETA',
    deploy_mode VARCHAR(20) DEFAULT 'client',
    source_id BIGINT NOT NULL,
    target_id BIGINT NOT NULL,
    source_name VARCHAR(100) DEFAULT NULL,
    target_name VARCHAR(100) DEFAULT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/GENERATED/RUNNING',
    description VARCHAR(500) DEFAULT NULL,
    enabled TINYINT(1) DEFAULT 0 COMMENT '是否在线启用调度',
    cron_expression VARCHAR(100) DEFAULT NULL COMMENT 'Cron 定时表达式',
    schedule_enabled TINYINT(1) DEFAULT 0 COMMENT '是否启用定时调度',
    last_exec_status VARCHAR(20) DEFAULT 'NONE' COMMENT 'NONE/SUCCESS/FAILED/RUNNING',
    last_exec_time TIMESTAMP NULL COMMENT '上次执行时间',
    last_exec_duration VARCHAR(50) DEFAULT NULL COMMENT '上次执行耗时',
    last_exec_rows BIGINT DEFAULT NULL COMMENT '上次执行写入行数',
    last_exec_qps VARCHAR(20) DEFAULT NULL COMMENT '上次执行QPS',
    incremental_where TEXT DEFAULT NULL COMMENT '增量WHERE条件（自由输入）',
    schema_save_mode VARCHAR(50) DEFAULT 'CREATE_SCHEMA_WHEN_NOT_EXIST' COMMENT '目标表结构处理策略',
    data_save_mode VARCHAR(50) DEFAULT 'APPEND_DATA' COMMENT '目标表数据处理策略',
    cluster_id BIGINT DEFAULT NULL COMMENT '关联集群客户端ID',
    seatunnel_config TEXT DEFAULT NULL,
    created_by VARCHAR(50) DEFAULT 'admin' COMMENT '创建人',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sync_task_table (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    task_id BIGINT NOT NULL,
    source_database VARCHAR(100) NOT NULL,
    source_table VARCHAR(100) NOT NULL,
    target_database VARCHAR(100) NOT NULL,
    target_table VARCHAR(100) NOT NULL,
    partition_column VARCHAR(100) DEFAULT NULL,
    sync_type VARCHAR(20) NOT NULL,
    sr_ddl TEXT DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (task_id) REFERENCES sync_task(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS task_execution (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    task_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/RUNNING/SUCCESS/FAILED',
    log_text MEDIUMTEXT DEFAULT NULL COMMENT '执行日志',
    triggered_by VARCHAR(50) DEFAULT 'admin' COMMENT '触发人',
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP NULL,
    FOREIGN KEY (task_id) REFERENCES sync_task(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(200) NOT NULL,
    real_name VARCHAR(50) DEFAULT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER' COMMENT 'ADMIN/USER',
    enabled TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_permission (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    datasource_id BIGINT NOT NULL,
    can_execute_sql TINYINT(1) DEFAULT 0,
    FOREIGN KEY (user_id) REFERENCES sys_user(id) ON DELETE CASCADE,
    FOREIGN KEY (datasource_id) REFERENCES datasource(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS operation_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) DEFAULT NULL,
    action VARCHAR(20) DEFAULT NULL,
    target VARCHAR(200) DEFAULT NULL,
    detail VARCHAR(500) DEFAULT NULL,
    ip VARCHAR(50) DEFAULT NULL,
    success TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cluster_client (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    client_name VARCHAR(100) NOT NULL COMMENT '客户端名称',
    host VARCHAR(200) NOT NULL COMMENT 'IP地址',
    port INT NOT NULL DEFAULT 8030 COMMENT '端口',
    status VARCHAR(20) DEFAULT 'OFFLINE' COMMENT 'ONLINE/OFFLINE',
    cpu_usage DOUBLE DEFAULT 0 COMMENT 'CPU使用率(%)',
    memory_usage DOUBLE DEFAULT 0 COMMENT '内存使用率(%)',
    ssh_port INT DEFAULT 22 COMMENT 'SSH端口',
    ssh_user VARCHAR(100) DEFAULT NULL COMMENT 'SSH用户名',
    ssh_password VARCHAR(200) DEFAULT NULL COMMENT 'SSH密码(已加密)',
    seatunnel_home VARCHAR(500) DEFAULT NULL COMMENT 'SeaTunnel安装目录',
    description VARCHAR(500) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alert_config (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL COMMENT '告警配置名称',
    type VARCHAR(20) NOT NULL COMMENT 'DINGTALK/FEISHU',
    webhook_url VARCHAR(500) NOT NULL COMMENT 'Webhook地址',
    secret VARCHAR(200) DEFAULT NULL COMMENT '签名密钥',
    keyword VARCHAR(100) DEFAULT NULL COMMENT '安全关键词',
    template TEXT DEFAULT NULL COMMENT '自定义告警模板',
    enabled TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
    event_types VARCHAR(50) NOT NULL DEFAULT 'FAILURE' COMMENT 'FAILURE/SUCCESS/ALL',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
